-- ---------------------------------------------------------------------
-- Read views used by the API
-- ---------------------------------------------------------------------
CREATE VIEW v_tracks AS
SELECT t.id,
       t.title,
       t.duration_ms,
       t.disc_number,
       t.track_number,
       t.genre,
       t.release_year,
       t.explicit,
       t.is_favorite,
       t.favorited_at,
       t.rating,
       t.play_count,
       t.last_played_at,
       t.created_at,
       ar.id              AS artist_id,
       ar.name            AS artist_name,
       al.id              AS album_id,
       al.title           AS album_title,
       al.cover_path,
       al.dominant_color,
       EXISTS (SELECT 1 FROM media_sources ms
                WHERE ms.track_id = t.id AND ms.is_available AND ms.kind = 'audio') AS has_audio,
       EXISTS (SELECT 1 FROM media_sources ms
                WHERE ms.track_id = t.id AND ms.is_available AND ms.kind = 'video') AS has_video,
       EXISTS (SELECT 1 FROM lyrics ly
                WHERE ly.track_id = t.id AND ly.synced_lines IS NOT NULL)          AS has_synced_lyrics
  FROM tracks t
  LEFT JOIN artists ar ON ar.id = t.primary_artist_id
  LEFT JOIN albums  al ON al.id = t.album_id;

CREATE VIEW v_playlists AS
SELECT p.id,
       p.name,
       p.description,
       p.cover_path,
       p.dominant_color,
       p.is_pinned,
       p.keep_offline,
       p.smart_rules,
       p.created_at,
       p.updated_at,
       s.track_count,
       s.total_duration_ms
  FROM playlists p
  CROSS JOIN LATERAL (
        SELECT count(*)::integer                  AS track_count,
               COALESCE(sum(t.duration_ms), 0)::bigint AS total_duration_ms
          FROM playlist_tracks pt
          JOIN tracks t ON t.id = pt.track_id
         WHERE pt.playlist_id = p.id
  ) s;

COMMIT;
