\set ON_ERROR_STOP on

BEGIN;

CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;
CREATE SCHEMA IF NOT EXISTS music;
SET LOCAL search_path = music, public;

-- ---------------------------------------------------------------------
-- Enum types
-- ---------------------------------------------------------------------
CREATE TYPE media_kind    AS ENUM ('audio', 'video');
CREATE TYPE source_origin AS ENUM ('local', 'remote');
CREATE TYPE artist_role   AS ENUM ('primary', 'featured', 'composer', 'producer', 'remixer');
CREATE TYPE repeat_mode   AS ENUM ('off', 'all', 'one');
CREATE TYPE play_context  AS ENUM ('library', 'album', 'artist', 'playlist', 'search', 'queue', 'radio');
CREATE TYPE scan_status   AS ENUM ('idle', 'scanning', 'error');

-- ---------------------------------------------------------------------
-- Shared trigger: keep updated_at fresh on every UPDATE
-- ---------------------------------------------------------------------
CREATE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------
-- library_folders: local directories the scanner indexes
-- ---------------------------------------------------------------------
CREATE TABLE library_folders (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path                   text        NOT NULL UNIQUE CHECK (btrim(path) <> ''),
    is_enabled             boolean     NOT NULL DEFAULT true,
    recursive              boolean     NOT NULL DEFAULT true,
    status                 scan_status NOT NULL DEFAULT 'idle',
    last_scan_started_at   timestamptz,
    last_scan_finished_at  timestamptz,
    last_scan_file_count   integer     CHECK (last_scan_file_count >= 0),
    last_error             text,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER library_folders_updated_at BEFORE UPDATE ON library_folders
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- artists
-- ---------------------------------------------------------------------
CREATE TABLE artists (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text        NOT NULL CHECK (btrim(name) <> ''),
    sort_name     text,                                  -- "Beatles, The"
    image_path    text,                                  -- cached artist image (relative to COVER_CACHE_DIR)
    bio           text,
    external_ids  jsonb       NOT NULL DEFAULT '{}'::jsonb,  -- {"musicbrainz": "...", "youtube_channel": "..."}
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT artists_external_ids_obj CHECK (jsonb_typeof(external_ids) = 'object')
);
CREATE UNIQUE INDEX artists_name_uniq ON artists (lower(name));
CREATE INDEX artists_name_trgm ON artists USING gin (lower(name) gin_trgm_ops);
CREATE TRIGGER artists_updated_at BEFORE UPDATE ON artists
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- albums
-- ---------------------------------------------------------------------
CREATE TABLE albums (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            text        NOT NULL CHECK (btrim(title) <> ''),
    album_artist_id  bigint      REFERENCES artists (id) ON DELETE SET NULL,
    album_type       text        NOT NULL DEFAULT 'album'
                                 CHECK (album_type IN ('album', 'single', 'ep', 'compilation', 'live')),
    release_date     date,
    release_year     smallint    CHECK (release_year BETWEEN 1000 AND 9999),
    genre            text,
    total_tracks     smallint    CHECK (total_tracks > 0),
    total_discs      smallint    CHECK (total_discs > 0),
    cover_path       text,                               -- extracted art, relative to COVER_CACHE_DIR
    cover_hash       text,                               -- sha1 of art bytes; dedupes identical covers
    dominant_color   text        CHECK (dominant_color ~ '^#[0-9a-fA-F]{6}$'),  -- server-side fallback for ambient theme
    palette          jsonb       CHECK (palette IS NULL OR jsonb_typeof(palette) = 'array'),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);
-- Same title by the same album-artist = same album (NULL artist treated as one bucket).
CREATE UNIQUE INDEX albums_artist_title_uniq ON albums (album_artist_id, lower(title)) NULLS NOT DISTINCT;
CREATE INDEX albums_title_trgm ON albums USING gin (lower(title) gin_trgm_ops);
CREATE INDEX albums_release_idx ON albums (release_year DESC NULLS LAST);
CREATE TRIGGER albums_updated_at BEFORE UPDATE ON albums
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- tracks: the logical song. Physical files/streams live in media_sources.
-- ---------------------------------------------------------------------
CREATE TABLE tracks (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                text        NOT NULL CHECK (btrim(title) <> ''),
    album_id             bigint      REFERENCES albums (id)  ON DELETE SET NULL,
    primary_artist_id    bigint      REFERENCES artists (id) ON DELETE SET NULL,
    disc_number          smallint    NOT NULL DEFAULT 1 CHECK (disc_number > 0),
    track_number         smallint    CHECK (track_number > 0),
    duration_ms          integer     CHECK (duration_ms >= 0),
    genre                text,
    release_year         smallint    CHECK (release_year BETWEEN 1000 AND 9999),
    isrc                 text        CHECK (isrc ~ '^[A-Z]{2}[A-Z0-9]{3}[0-9]{7}$'),
    bpm                  numeric(5,1) CHECK (bpm > 0),
    explicit             boolean     NOT NULL DEFAULT false,
    replaygain_track_db  numeric(5,2),
    replaygain_album_db  numeric(5,2),
    is_favorite          boolean     NOT NULL DEFAULT false,   -- "Liked Songs"
    favorited_at         timestamptz,
    rating               smallint    CHECK (rating BETWEEN 0 AND 5),
    play_count           integer     NOT NULL DEFAULT 0 CHECK (play_count >= 0),
    skip_count           integer     NOT NULL DEFAULT 0 CHECK (skip_count >= 0),
    last_played_at       timestamptz,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT tracks_favorite_ts CHECK (is_favorite OR favorited_at IS NULL)
);
CREATE INDEX tracks_album_order_idx ON tracks (album_id, disc_number, track_number);
CREATE INDEX tracks_artist_idx      ON tracks (primary_artist_id);
CREATE INDEX tracks_title_trgm      ON tracks USING gin (lower(title) gin_trgm_ops);
CREATE INDEX tracks_favorites_idx   ON tracks (favorited_at DESC) WHERE is_favorite;
CREATE INDEX tracks_created_idx     ON tracks (created_at DESC);           -- "Recently added"
CREATE INDEX tracks_most_played_idx ON tracks (play_count DESC) WHERE play_count > 0;
CREATE TRIGGER tracks_updated_at BEFORE UPDATE ON tracks
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- track_artists: features, composers, remixers (many-to-many)
-- ---------------------------------------------------------------------
CREATE TABLE track_artists (
    track_id   bigint      NOT NULL REFERENCES tracks (id)  ON DELETE CASCADE,
    artist_id  bigint      NOT NULL REFERENCES artists (id) ON DELETE CASCADE,
    role       artist_role NOT NULL DEFAULT 'primary',
    position   smallint    NOT NULL DEFAULT 0 CHECK (position >= 0),  -- display order in "A, B feat. C"
    PRIMARY KEY (track_id, artist_id, role)
);
CREATE INDEX track_artists_artist_idx ON track_artists (artist_id, role);

-- ---------------------------------------------------------------------
-- media_sources: every playable rendition of a track.
--   One track can have e.g. a local FLAC (audio) + a YouTube video (video),
--   which is what makes the Song/Video mode switch possible.
-- ---------------------------------------------------------------------
CREATE TABLE media_sources (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id           bigint        NOT NULL REFERENCES tracks (id) ON DELETE CASCADE,
    kind               media_kind    NOT NULL,
    origin             source_origin NOT NULL,

    -- origin = 'local'
    file_path          text,                          -- absolute path on the server
    file_size_bytes    bigint        CHECK (file_size_bytes >= 0),
    file_mtime         timestamptz,                   -- rescan skips unchanged files

    -- origin = 'remote' (resolved via yt-dlp)
    extractor          text,                          -- 'youtube', 'soundcloud', ...
    remote_id          text,                          -- e.g. YouTube video id
    page_url           text,                          -- canonical page URL
    format_id          text,                          -- yt-dlp format selected
    cached_stream_url  text,                          -- direct googlevideo/CDN URL (short-lived)
    stream_expires_at  timestamptz,                   -- re-resolve after this
    stream_headers     jsonb         CHECK (stream_headers IS NULL OR jsonb_typeof(stream_headers) = 'object'),

    -- technical metadata
    mime_type          text,
    container          text,                          -- mp3, flac, m4a, webm, mp4
    audio_codec        text,
    video_codec        text,
    bitrate_kbps       integer       CHECK (bitrate_kbps > 0),
    sample_rate_hz     integer       CHECK (sample_rate_hz > 0),
    bit_depth          smallint      CHECK (bit_depth > 0),
    channels           smallint      CHECK (channels > 0),
    width              integer       CHECK (width > 0),
    height             integer       CHECK (height > 0),
    fps                numeric(6,3)  CHECK (fps > 0),
    duration_ms        integer       CHECK (duration_ms >= 0),

    -- Song<->Video sync: video_position_ms = audio_position_ms + sync_offset_ms
    -- (music videos often have intros the album cut lacks). Set on video rows.
    sync_offset_ms     integer       NOT NULL DEFAULT 0,

    is_preferred       boolean       NOT NULL DEFAULT false,  -- default pick per (track, kind)
    is_available       boolean       NOT NULL DEFAULT true,   -- false when file vanished on rescan
    created_at         timestamptz   NOT NULL DEFAULT now(),
    updated_at         timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT media_sources_origin_fields CHECK (
        (origin = 'local'  AND file_path IS NOT NULL)
     OR (origin = 'remote' AND extractor IS NOT NULL AND remote_id IS NOT NULL AND page_url IS NOT NULL)
    ),
    CONSTRAINT media_sources_dims_pair CHECK ((width IS NULL) = (height IS NULL))
);
CREATE INDEX media_sources_track_idx ON media_sources (track_id, kind) WHERE is_available;
CREATE UNIQUE INDEX media_sources_local_uniq  ON media_sources (file_path, kind)
    WHERE origin = 'local';
CREATE UNIQUE INDEX media_sources_remote_uniq ON media_sources (extractor, remote_id, kind)
    WHERE origin = 'remote';
CREATE UNIQUE INDEX media_sources_one_preferred ON media_sources (track_id, kind)
    WHERE is_preferred;
CREATE TRIGGER media_sources_updated_at BEFORE UPDATE ON media_sources
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- lyrics: plain + time-synced (LRC parsed into JSON)
-- synced_lines format: [{"t": 12340, "text": "First line"}, ...] sorted by t (ms)
-- ---------------------------------------------------------------------
CREATE TABLE lyrics (
    track_id      bigint      PRIMARY KEY REFERENCES tracks (id) ON DELETE CASCADE,
    plain_text    text,
    synced_lines  jsonb       CHECK (synced_lines IS NULL OR jsonb_typeof(synced_lines) = 'array'),
    offset_ms     integer     NOT NULL DEFAULT 0,      -- user nudge for out-of-sync LRCs
    language      text,
    source        text        NOT NULL DEFAULT 'embedded'
                              CHECK (source IN ('embedded', 'lrc_file', 'manual', 'remote')),
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT lyrics_not_empty CHECK (plain_text IS NOT NULL OR synced_lines IS NOT NULL)
);
CREATE TRIGGER lyrics_updated_at BEFORE UPDATE ON lyrics
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- playlists
-- ---------------------------------------------------------------------
CREATE TABLE playlists (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text        NOT NULL CHECK (btrim(name) <> ''),
    description     text,
    cover_path      text,                     -- NULL => UI builds a 2x2 mosaic
    dominant_color  text        CHECK (dominant_color ~ '^#[0-9a-fA-F]{6}$'),
    is_pinned       boolean     NOT NULL DEFAULT false,
    keep_offline    boolean     NOT NULL DEFAULT false,  -- service worker pre-caches all tracks
