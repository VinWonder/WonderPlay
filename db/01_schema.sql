CREATE INDEX playlists_sidebar_idx ON playlists (is_pinned DESC, updated_at DESC);
CREATE TRIGGER playlists_updated_at BEFORE UPDATE ON playlists
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- playlist_tracks: ordered items; the same track may appear more than once.
-- Position uniqueness is DEFERRED so reorders can shuffle rows freely
-- inside one transaction.
-- ---------------------------------------------------------------------
CREATE TABLE playlist_tracks (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id  bigint      NOT NULL REFERENCES playlists (id) ON DELETE CASCADE,
    track_id     bigint      NOT NULL REFERENCES tracks (id)    ON DELETE CASCADE,
    position     integer     NOT NULL CHECK (position >= 0),
    added_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT playlist_tracks_position_uniq UNIQUE (playlist_id, position)
        DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX playlist_tracks_track_idx ON playlist_tracks (track_id);

-- Touch the parent playlist so clients (and the offline cache) can detect changes.
CREATE FUNCTION playlist_tracks_touch_parent() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE playlists
       SET updated_at = now()
     WHERE id = COALESCE(NEW.playlist_id, OLD.playlist_id);
    RETURN NULL;
END;
$$;
CREATE TRIGGER playlist_tracks_touch AFTER INSERT OR UPDATE OR DELETE ON playlist_tracks
    FOR EACH ROW EXECUTE FUNCTION playlist_tracks_touch_parent();

-- Move one playlist item to a 0-based position and compact all positions
-- to 0..n-1 (also closes gaps left by deletions).
CREATE FUNCTION playlist_move_item(p_item_id bigint, p_new_position integer) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    v_playlist_id bigint;
BEGIN
    SELECT playlist_id INTO v_playlist_id FROM playlist_tracks WHERE id = p_item_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'playlist item % not found', p_item_id USING ERRCODE = 'no_data_found';
    END IF;

    -- Serialize concurrent edits of the same playlist.
    PERFORM 1 FROM playlists WHERE id = v_playlist_id FOR UPDATE;

    WITH others AS (
        SELECT id, (row_number() OVER (ORDER BY position, id) - 1)::integer AS rn
          FROM playlist_tracks
         WHERE playlist_id = v_playlist_id AND id <> p_item_id
    ),
    clamped AS (
        SELECT LEAST(GREATEST(p_new_position, 0), (SELECT count(*) FROM others)::integer) AS pos
    ),
    target AS (
        SELECT o.id, CASE WHEN o.rn >= c.pos THEN o.rn + 1 ELSE o.rn END AS new_pos
          FROM others o CROSS JOIN clamped c
        UNION ALL
        SELECT p_item_id, c.pos FROM clamped c
    )
    UPDATE playlist_tracks pt
       SET position = t.new_pos
      FROM target t
     WHERE pt.id = t.id
       AND pt.position <> t.new_pos;
END;
$$;

-- ---------------------------------------------------------------------
-- play_history: one row per finished listening session.
-- The backend inserts the row when a track ends, is skipped, or is
-- replaced, so the stats trigger below sees final values.
-- ---------------------------------------------------------------------
CREATE TABLE play_history (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id      bigint       NOT NULL REFERENCES tracks (id) ON DELETE CASCADE,
    source_id     bigint       REFERENCES media_sources (id) ON DELETE SET NULL,
    mode          media_kind   NOT NULL DEFAULT 'audio',
    context_type  play_context NOT NULL DEFAULT 'library',
    context_id    bigint,                              -- album/playlist/artist id when applicable
    started_at    timestamptz  NOT NULL DEFAULT now(),
    ended_at      timestamptz,
    played_ms     integer      NOT NULL DEFAULT 0 CHECK (played_ms >= 0),
    completed     boolean      NOT NULL DEFAULT false,
    skipped       boolean      NOT NULL DEFAULT false,
    was_offline   boolean      NOT NULL DEFAULT false, -- synced later from the PWA's offline log
    device        text,
    CONSTRAINT play_history_time_order CHECK (ended_at IS NULL OR ended_at >= started_at),
    CONSTRAINT play_history_outcome    CHECK (NOT (completed AND skipped))
);
CREATE INDEX play_history_recent_idx ON play_history (started_at DESC);
CREATE INDEX play_history_track_idx  ON play_history (track_id, started_at DESC);
CREATE INDEX play_history_context_idx ON play_history (context_type, context_id, started_at DESC)
    WHERE context_id IS NOT NULL;

-- A play counts after completion or 30 s of listening (Spotify's rule).
CREATE FUNCTION play_history_apply_stats() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE tracks
       SET play_count     = play_count + CASE WHEN NEW.completed OR NEW.played_ms >= 30000 THEN 1 ELSE 0 END,
           skip_count     = skip_count + CASE WHEN NEW.skipped THEN 1 ELSE 0 END,
           last_played_at = GREATEST(last_played_at, NEW.started_at)
     WHERE id = NEW.track_id;
    RETURN NULL;
END;
$$;
CREATE TRIGGER play_history_stats AFTER INSERT ON play_history
    FOR EACH ROW EXECUTE FUNCTION play_history_apply_stats();

